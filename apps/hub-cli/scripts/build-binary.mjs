// Builds the single-file `bun --compile` executable that ships the hub with no
// Node.js required. The frontend has no directory to live in inside a self-
// contained binary, so it is embedded: every file in `apps/web/dist` is staged
// under `bun/web`, a generated module imports each with `{ type: "file" }` so
// `bun build --compile` embeds it, and the binary reads it back with `Bun.file`.
//
// Bun is an undeclared toolchain with no CI: this is a local-only build. It is
// resolved off `PATH` or `~/.bun/bin/bun`, and a clear error is raised when it
// is nowhere to be found.
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, posix, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const hubCliDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const webDist = join(hubCliDir, "..", "web", "dist");
const bunDir = join(hubCliDir, "bun");
const stagedWeb = join(bunDir, "web");
const binariesDir = join(hubCliDir, "binaries");

if (!existsSync(join(webDist, "index.html"))) {
  fail(
    `no frontend at ${webDist}.\n` +
      "Build the frontend first — `pnpm build:binary` from the repo root does this in order.",
  );
}

const bun = resolveBun();

// Stage the frontend locally so the generated imports are self-contained and
// resolve regardless of where the compile runs from.
rmSync(stagedWeb, { recursive: true, force: true });
cpSync(webDist, stagedWeb, { recursive: true });

const files = walk(stagedWeb).sort();
generateEmbedModule(files);

mkdirSync(binariesDir, { recursive: true });

// No target given → the host platform. Named targets (`bun-darwin-arm64`,
// `bun-windows-x64`) cross-compile from here, though nothing on a Linux host can
// run them.
const targets = process.argv.slice(2);
if (targets.length === 0) targets.push("");

for (const target of targets) {
  const suffix = target === "" ? "" : `-${target}`;
  const extension = target.startsWith("bun-windows") ? ".exe" : "";
  const outfile = join(binariesDir, `co-canvas-hub${suffix}${extension}`);
  const args = ["build", "--compile"];
  if (target !== "") args.push(`--target=${target}`);
  args.push("bun/main.ts", "--outfile", outfile);

  process.stdout.write(`co-canvas hub-cli: compiling ${outfile}\n`);
  const result = spawnSync(bun, args, { cwd: hubCliDir, stdio: "inherit" });
  if (result.status !== 0)
    fail(`\`bun ${args.join(" ")}\` exited with ${result.status ?? result.signal}`);
}

function generateEmbedModule(absoluteFiles) {
  const imports = [];
  const entries = [];
  absoluteFiles.forEach((absolute, index) => {
    const fromBun = relative(bunDir, absolute).split(sep).join(posix.sep);
    const key = relative(stagedWeb, absolute).split(sep).join(posix.sep);
    imports.push(`import _${index} from "./${fromBun}" with { type: "file" };`);
    entries.push(`  [${JSON.stringify(key)}, _${index}],`);
  });

  const source = `// AUTO-GENERATED by scripts/build-binary.mjs — do not edit, and do not commit.
// Each import embeds one frontend file into the compiled binary; \`Bun.file\`
// reads it back at runtime.
import { file } from "bun";
${imports.join("\n")}

const entries: [string, string][] = [
${entries.join("\n")}
];

/** Reads every embedded frontend file into a map keyed by its relative POSIX path. */
export async function loadEmbeddedAssets(): Promise<Map<string, Uint8Array>> {
  const assets = new Map<string, Uint8Array>();
  for (const [key, path] of entries) {
    assets.set(key, new Uint8Array(await file(path).arrayBuffer()));
  }
  return assets;
}
`;

  writeFileSync(join(bunDir, "embedded-assets.ts"), source, "utf8");
  process.stdout.write(`co-canvas hub-cli: embedded ${absoluteFiles.length} frontend files\n`);
}

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full));
    else if (entry.isFile()) out.push(full);
  }
  return out;
}

function resolveBun() {
  const onPath = spawnSync("bun", ["--version"], { stdio: "ignore" });
  if (onPath.status === 0) return "bun";
  const wellKnown = join(homedir(), ".bun", "bin", "bun");
  if (existsSync(wellKnown)) return wellKnown;
  fail(
    "bun is required to build the standalone binary but was not found on PATH or at ~/.bun/bin/bun.\n" +
      "Install it from https://bun.sh, then run this again.",
  );
  return "";
}

function fail(message) {
  process.stderr.write(`co-canvas hub-cli build:binary: ${message}\n`);
  process.exit(1);
}
